import { useEffect, useId, useRef, useState } from "react";
import mermaid from "mermaid";
import { Check, Copy, Maximize2 } from "lucide-react";
import { Button, Card, CardTitle } from "./ui";

let renderSequence = 0;

mermaid.initialize({
  startOnLoad: false,
  suppressErrorRendering: true,
  theme: "base",
  securityLevel: "strict",
  fontFamily: "Inter, ui-sans-serif, system-ui, sans-serif",
  themeVariables: {
    background: "#ffffff",
    primaryColor: "#f1f5f9",
    primaryBorderColor: "#94a3b8",
    primaryTextColor: "#0f172a",
    lineColor: "#94a3b8",
    fontSize: "13px",
  },
  flowchart: { curve: "basis", padding: 14, nodeSpacing: 40, rankSpacing: 56 },
});

export function GraphView({ graph, title = "Dependency graph" }: { graph: string; title?: string }) {
  const container = useRef<HTMLDivElement>(null);
  const [error, setError] = useState("");
  const [copied, setCopied] = useState(false);
  const rawId = useId().replace(/[^a-zA-Z0-9]/g, "");

  useEffect(() => {
    let cancelled = false;
    const target = container.current;
    setError("");
    if (!graph || !target) return;
    target.innerHTML = "";
    const renderId = `fortcloud-graph-${rawId}-${++renderSequence}`;
    mermaid
      .render(renderId, graph, target)
      .then(({ svg }) => {
        if (!cancelled && container.current) container.current.innerHTML = svg;
      })
      .catch((cause: unknown) => {
        target.innerHTML = "";
        if (!cancelled) setError(cause instanceof Error ? cause.message : String(cause));
      });
    return () => {
      cancelled = true;
      if (container.current) container.current.innerHTML = "";
    };
  }, [graph, rawId]);

  const copy = async () => {
    await navigator.clipboard.writeText(graph);
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1500);
  };

  return (
    <Card>
      <CardTitle
        title={title}
        subtitle="Generated by the tool. Arrow A → B means A depends on B."
        action={
          <div className="flex gap-2">
            <Button onClick={copy}>
              {copied ? <Check className="h-3.5 w-3.5" /> : <Copy className="h-3.5 w-3.5" />}
              {copied ? "Copied" : "Copy Mermaid"}
            </Button>
            <Button
              aria-label="Expand graph"
              title="Expand graph"
              onClick={() => {
                const svg = container.current?.querySelector("svg");
                if (!document.fullscreenElement && svg) {
                  void svg.requestFullscreen?.();
                }
              }}
            >
              <Maximize2 className="h-3.5 w-3.5" />
            </Button>
          </div>
        }
      />
      {error ? (
        <div className="rounded-lg bg-rose-50 p-4 text-xs text-rose-700">
          The graph could not be rendered: {error}
        </div>
      ) : (
        <div
          ref={container}
          className="min-h-[340px] overflow-auto rounded-lg border border-slate-100 bg-[radial-gradient(#e2e8f0_1px,transparent_1px)] [background-size:18px_18px] p-4 [&_svg]:mx-auto [&_svg]:max-w-full"
        />
      )}
    </Card>
  );
}
