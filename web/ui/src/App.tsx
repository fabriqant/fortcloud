    "Use this tab to understand required fields, allowed enum values, numeric bounds and pattern constraints when a field rejects a value.",
    "Each schema maps to one model file; the selected file is shown as raw JSON so nothing is hidden behind the form.",
    "Catalog-backed enums are suggestions, not a hard limit: the form allows custom values, but validation still applies when you save or run Check.",
