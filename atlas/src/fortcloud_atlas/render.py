"""Mermaid graph and resilience report generation."""

from __future__ import annotations

from collections import Counter
from datetime import date
from pathlib import Path

from . import core


def escape(label: str) -> str:
    return str(label).replace('"', "'").replace("\n", " ")


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join(["---"] * len(headers)) + "|",
    ]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines


def build_graph(model: dict) -> str:
    lines = [
        "```mermaid",
        "flowchart LR",
        "  classDef p0 fill:#fde2e2,stroke:#c0392b,color:#2b1a1a;",
        "  classDef p1 fill:#fff3cd,stroke:#b8860b,color:#3b2f00;",
        "  classDef p2 fill:#e8f5e9,stroke:#2e7d32,color:#183b1a;",
        "",
    ]
    for component in sorted(model["components"], key=lambda item: item["id"]):
        category = core.CATEGORY_LABELS.get(component["category"], component["category"])
        label = f"{escape(component['name'])}<br/>{escape(category)}"
        lines.append(f"  {component['id']}[\"{label}\"]:::{component['criticality'].lower()}")
    lines.append("")
    for dependency in sorted(model["dependencies"], key=lambda item: item["id"]):
        arrow = "-.->" if not dependency["required"] else "-->"
        lines.append(f"  {dependency['from']} {arrow}|{dependency['kind']}| {dependency['to']}")
    lines.append("```")
    return "\n".join(lines)


def build_graph_document(model: dict) -> str:
    inbound = Counter(dep["to"] for dep in model["dependencies"])
    doc = [
        "# Dependency graph",
        "",
        "> Generated by `fortcloud-atlas graph`. Edit `dependencies.yaml` instead.",
        "",
        "An arrow `A --> B` means **A depends on B**. The more arrows a node receives,",
        "the larger its blast radius. Dotted links are non-critical dependencies (`required: false`).",
        "",
        build_graph(model),
        "",
        "## Legend",
        "",
        "| Colour | Criticality | Meaning |",
        "|---|---|---|",
        "| Red | P0 | Critical — interruption unacceptable |",
        "| Amber | P1 | Important — short degradation tolerated |",
        "| Green | P2 | Support — recovery in hours |",
        "",
        "## Most depended-upon nodes (blast radius)",
        "",
        "| Component | Category | Criticality | Direct dependents |",
        "|---|---|---|---|",
    ]
    ranked = sorted(model["components"], key=lambda item: (-inbound[item["id"]], item["id"]))
    for component in ranked[:8]:
        doc.append(
            f"| `{component['id']}` — {component['name']} | "
            f"{core.CATEGORY_LABELS.get(component['category'], component['category'])} | "
            f"{component['criticality']} | {inbound[component['id']]} |"
        )
    doc += ["", "See also: [resilience report](resilience-report.md).", ""]
    return "\n".join(doc)


def build_report(model: dict, today: date | None = None) -> str:
    today = today or date.today()
    inbound = Counter(dep["to"] for dep in model["dependencies"])
    risks = sorted(model["risks"], key=lambda item: (-core.risk_score(item), item["id"]))
    active_risks = [risk for risk in risks if risk["status"] != "closed"]

    spofs = [component for component in model["components"] if core.is_spof(component)]
    single_region = [component for component in model["components"] if core.is_single_region_p0(component)]
    critical_risks = [risk for risk in risks if core.risk_score(risk) >= 15]

    doc = [
        "# FortCloud Atlas — Resilience Report",
        "",
        f"> Generated on {today.isoformat()} by `fortcloud-atlas report`. Do not edit by hand.",
        "",
        "## Summary",
        "",
        f"- **{len(model['components'])}** components "
        f"(P0: {sum(1 for c in model['components'] if c['criticality'] == 'P0')}, "
        f"P1: {sum(1 for c in model['components'] if c['criticality'] == 'P1')}, "
        f"P2: {sum(1 for c in model['components'] if c['criticality'] == 'P2')})",
        f"- **{len(model['flows'])}** business flows",
        f"- **{len(model['dependencies'])}** dependencies",
        f"- **{len(spofs)}** single points of failure (single instance)",
        f"- **{len(single_region)}** P0 components in a single region",
        f"- **{len(critical_risks)}** critical risks (score >= 15)",
        "",
        "## Single points of failure",
        "",
        "These components have a single instance. Losing one directly impacts every",
        "flow that depends on it — or blocks deployments for support components.",
        "",
    ]
    rows = []
    for component in sorted(spofs, key=lambda item: (item["criticality"], item["id"])):
        linked = [risk for risk in active_risks if component["id"] in risk["components"]]
        rows.append(
            [
                f"`{component['id']}` — {component['name']}",
                core.CATEGORY_LABELS.get(component["category"], component["category"]),
                component["criticality"],
                component["owner"],
                inbound[component["id"]],
                ", ".join(risk["id"] for risk in linked) or "**none**",
                linked[0]["action"] if linked else "Prioritise this item",
            ]
        )
    doc += _table(
        ["Component", "Category", "Criticality", "Owner", "Dependents", "Risks", "Action"], rows
    )

    doc += ["", "### P0 components in a single region", ""]
    if single_region:
        doc += _table(
            ["Component", "Regions", "Provider", "Owner"],
            [
                [f"`{c['id']}`", ", ".join(c["regions"]), c["provider"], c["owner"]]
                for c in sorted(single_region, key=lambda item: item["id"])
            ],
        )
    else:
        doc.append("None.")

    doc += [
        "",
        "## RTO / RPO matrix",
        "",
        "RTO = maximum time to restore service. RPO = maximum acceptable data loss.",
        "",
    ]
    rows = []
    for flow in sorted(model["flows"], key=lambda item: (item["criticality"], item["id"])):
        age = core.test_age_days(flow["last_restore_test"], today)
        age_label = "missing" if age is None else f"{age} d"
        if age is not None and age > core.TEST_MAX_AGE_DAYS:
            age_label = f"**{age} d (stale)**"
        rows.append(
            [
                f"`{flow['id']}` — {flow['name']}",
                flow["criticality"],
                flow["availability_target"],
                flow["rto"],
                flow["rpo"],
                flow["owner"],
                age_label,
            ]
        )
    doc += _table(
        ["Flow", "Criticality", "Availability", "RTO", "RPO", "Owner", "Last restore test"], rows
    )

    doc += ["", "### Recovery strategies", ""]
    for flow in sorted(model["flows"], key=lambda item: item["id"]):
        doc.append(f"- **{flow['id']}**: {flow['strategy']}")

    doc += [
        "",
        "## Risk register",
        "",
        "Sorted by descending score (likelihood × impact).",
        "",
    ]
    doc += _table(
        ["ID", "Risk", "Components", "Score", "Severity", "Status", "Owner", "Due"],
        [
            [
                risk["id"],
                risk["title"],
                ", ".join(f"`{item}`" for item in risk["components"]),
                core.risk_score(risk),
                core.severity(core.risk_score(risk)),
                risk["status"],
                risk["owner"],
                risk["target_date"],
            ]
            for risk in risks
        ],
    )

    doc += ["", "### Critical action plans", ""]
    for risk in critical_risks:
        doc.append(
            f"- **{risk['id']} — {risk['title']}** ({core.risk_score(risk)}): {risk['action']} "
            f"— {risk['owner']}, due {risk['target_date']}."
        )

    stale = []
    for flow in model["flows"]:
        age = core.test_age_days(flow["last_restore_test"], today)
        if age is None or age > core.TEST_MAX_AGE_DAYS:
            stale.append((flow["id"], flow["criticality"], age))
    doc += ["", "## Restore tests to refresh", ""]
    if stale:
        doc += _table(
            ["Flow", "Criticality", "Age of last test"],
            [
                [identifier, criticality, "missing" if age is None else f"{age} days"]
                for identifier, criticality, age in sorted(stale)
            ],
        )
        doc += [
            "",
            f"Rule: a restore test must be refreshed at least every {core.TEST_MAX_AGE_DAYS} days.",
        ]
    else:
        doc.append("All tests are up to date.")

    doc += [
        "",
        "## Links",
        "",
        "- [Dependency graph](dependency-graph.md)",
        "- [Concepts](../concepts.md)",
        "- [Quickstart](../quickstart.md)",
        "",
    ]
    return "\n".join(doc)


def write_graph(model: dict, output_dir: str | Path = core.DEFAULT_OUTPUT) -> Path:
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "dependency-graph.md"
    path.write_text(build_graph_document(model), encoding="utf-8")
    return path


def write_report(model: dict, output_dir: str | Path = core.DEFAULT_OUTPUT, today=None) -> Path:
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "resilience-report.md"
    path.write_text(build_report(model, today), encoding="utf-8")
    return path
